def generate_table_coco_benchmarks() -> str:
    """Table 8: Cross-Modal MS-COCO Retrieval (tab:coco_benchmarks_v3)."""
    csv_path = RESULTS_DIR / "v3" / "coco_native_visual_v3.csv"
    with open(csv_path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    import ast
    def parse_ci(val: str) -> tuple[float, float]:
        val = val.strip().strip('"')
        try:
            parsed = ast.literal_eval(val)
            return float(parsed[0]), float(parsed[1])
        except Exception:
            return 0.0, 0.0

    lines = []
    lines.append("% Auto-generated by scripts/make_tables.py from results/v3/coco_native_visual_v3.csv")
    lines.append("\\begin{table}[htbp]")
    lines.append("\\centering")
    lines.append("\\small")
    lines.append("\\caption{Cross-modal text-to-image retrieval performance on $N=1{,}000$ MS-COCO Karpathy-test images. Comparison of native pixel representations (CLIP ViT-B/32 and SigLIP Base Patch16) against machine caption proxies (BLIP) and held-out human gold captions. Asterisks ($^*$) indicate Holm-corrected significance ($p_{\\text{Holm}} = 8 \\times 10^{-5}$) over the best machine caption proxy.}")
    lines.append("\\label{tab:coco_benchmarks_v3}")
    lines.append("\\resizebox{\\columnwidth}{!}{%")
    lines.append("\\begin{tabular}{lcccc}")
    lines.append("\\toprule")
    lines.append("Method & Hit@1 & Hit@5 & Hit@10 [95\\% CI] & MRR [95\\% CI] \\\\")
    lines.append("\\midrule")

    sections = [
        ("\\textit{Machine Caption Proxy (BLIP)}", [0, 1, 2]),
        ("\\textit{Human Gold Caption Proxy (Upper Bound)}", [3, 4, 5]),
        ("\\textit{Native Pixel Representation}", [6, 7]),
        ("\\textit{Multi-Vector \\& Hybrid Fusion}", [8, 9, 10]),
    ]

    for sec_title, indices in sections:
        lines.append(f"\\multicolumn{{5}}{{l}}{{{sec_title}}} \\\\")
        for idx in indices:
            r = rows[idx]
            sys_name = r["System"].strip()
            h1 = float(r["Hit1"])
            h5 = float(r["Hit5"])
            h10 = float(r["Hit10"])
            h10_l, h10_u = parse_ci(r.get("Hit10_CI", ""))
            mrr = float(r["MRR"])
            mrr_l, mrr_u = parse_ci(r.get("MRR_CI", ""))

            sig = "$^*$" if idx in (6, 7) else ""
            if idx in (6, 7):
                sys_str = f"\\textbf{{{sys_name}}}"
                h1_str = f"\\textbf{{{h1:.4f}}}{sig}"
                h5_str = f"\\textbf{{{h5:.4f}}}{sig}"
                h10_str = f"\\textbf{{{h10:.4f}}}{sig} [{h10_l:.3f}, {h10_u:.3f}]"
                mrr_str = f"\\textbf{{{mrr:.4f}}}{sig} [{mrr_l:.3f}, {mrr_u:.3f}]"
            else:
                sys_str = sys_name
                h1_str = f"{h1:.4f}"
                h5_str = f"{h5:.4f}"
                h10_str = f"{h10:.4f} [{h10_l:.3f}, {h10_u:.3f}]"
                mrr_str = f"{mrr:.4f} [{mrr_l:.3f}, {mrr_u:.3f}]"

            lines.append(f"{sys_str:<30} & {h1_str} & {h5_str} & {h10_str} & {mrr_str} \\\\")
        lines.append("\\midrule" if sec_title != sections[-1][0] else "\\bottomrule")

    lines.append("\\end{tabular}}")
    lines.append("\\end{table}")
    return "\n".join(lines)


