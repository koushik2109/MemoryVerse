def generate_table_regime_grid() -> str:
    """Table 3: Multimodal Text-Proxy Retrieval Regime Analysis (tab:regime_grid_v3)."""
    csv_path = RESULTS_DIR / "v3" / "headline_regime_grid_v3.csv"
    with open(csv_path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    # Group by Query Type
    grouped: Dict[str, List[dict]] = {"verbatim": [], "light": [], "heavy": []}
    for r in rows:
        q = r["Query_Type"].strip().lower()
        if q in grouped:
            grouped[q].append(r)

    # In headline_regime_grid_v3.csv, columns are:
    # Query_Type, Condition, System, MRR, MRR_CI_Lower, MRR_CI_Upper, Hit10, Hit10_CI_Lower, Hit10_CI_Upper, Mean_Latency_ms, Dev_Alpha_Star
    # Reorganize by (Query_Type, System) -> {Condition: (MRR, CI_L, CI_U, Latency)}
    lines = []
    lines.append("% Auto-generated by scripts/make_tables.py from results/v3/headline_regime_grid_v3.csv")
    lines.append("\\begin{table*}[t]")
    lines.append("\\centering")
    lines.append("\\small")
    lines.append("\\caption{Multimodal Text-Proxy Retrieval Regime Analysis across Query Types and Noise Regimes (Held-Out Public Test Split, $N=306$ Probes, 813 Distractor Pool, 95\\% Cluster Bootstrap CIs). Dense MiniLM/BGE latencies (0.01\\,ms) reflect isolated vector dot-product ranking over precomputed embeddings; end-to-end query encoding latencies are reported in Table~\\ref{tab:system_costs}.}")
    lines.append("\\label{tab:regime_grid_v3}")
    lines.append("\\resizebox{\\textwidth}{!}{%")
    lines.append("\\begin{tabular}{llccccc}")
    lines.append("\\toprule")
    lines.append("Query Type & Retrieval System & Clean MRR [95\\% CI] & Syn 20\\% MRR [95\\% CI] & Real-OCR MRR [95\\% CI] & Optical Blur MRR [95\\% CI] & Latency (ms) \\\\")
    lines.append("\\midrule")

    q_order = [
        ("verbatim", "\\textbf{Verbatim}"),
        ("light", "\\textbf{Light Paraphrase}"),
        ("heavy", "\\textbf{Answerable Questions}"),
    ]

    sys_order = [
        ("BM25 (Tuned)", "BM25 (Tuned)"),
        ("BM25 (Char 3-5gram)", "BM25 (Char 3-5gram)"),
        ("Dense MiniLM (chunked)", "Dense MiniLM (unchunked)"),
        ("Dense BGE-base (chunked)", "Dense BGE-base (unchunked)"),
        ("Tuned Hybrid", "Tuned Hybrid"),
        ("CLIP Visual", "CLIP Visual"),
        ("Uniform Random Ranking", "Uniform Random Ranking"),
    ]

    for q_key, q_label in q_order:
        q_rows = grouped[q_key]
        grid_data: Dict[str, Dict[str, dict]] = {}
        for r in q_rows:
            sys_name = r["System"].strip()
            cond = r["Condition"].strip().lower()
            if sys_name not in grid_data:
                grid_data[sys_name] = {}
            grid_data[sys_name][cond] = r

        lines.append(f"\\multirow{{7}}{{*}}{{{q_label}}}")
        for raw_sys, display_sys in sys_order:
            if raw_sys not in grid_data:
                continue
            conds = grid_data[raw_sys]
            # conditions: ground_truth (Clean), syn_20, clean_ocr (Real-OCR), degraded_ocr (Optical Blur)
            c_gt = conds.get("ground_truth", {})
            c_syn = conds.get("syn_20", {})
            c_clean = conds.get("clean_ocr", {})
            c_deg = conds.get("degraded_ocr", {})

            def fmt_cell(c: dict) -> str:
                if not c: return "---"
                mrr = float(c["MRR"])
                l = float(c["MRR_CI_Lower"])
                u = float(c["MRR_CI_Upper"])
                return f"{mrr:.4f} [{l:.3f}, {u:.3f}]"

            lat = float(c_clean.get("Mean_Latency_ms", 0.01))
            lines.append(f" & {display_sys:<24} & {fmt_cell(c_gt)} & {fmt_cell(c_syn)} & {fmt_cell(c_clean)} & {fmt_cell(c_deg)} & {lat:.2f} \\\\")
        lines.append("\\midrule" if q_key != "heavy" else "\\bottomrule")

    lines.append("\\end{tabular}}")
    lines.append("\\end{table*}")
    return "\n".join(lines)


